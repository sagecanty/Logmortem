"""
formatter.py — formats RCA dict into markdown and terminal output
"""

import re
from datetime import datetime

# SECURITY (THREAT_MODEL T6): everything the model writes is derived from
# untrusted log content, and this markdown is rendered in GitHub's job
# summary. Model text must render as plain text: no links, images, raw
# HTML, headings or broken tables. md() is applied to every model field
# and to context values an attacker can influence (alert, log group).
_MD_SPECIAL = re.compile(r"([\\`*_\[\]|#])")


def md(value) -> str:
    """Render untrusted text as inert, single-line markdown."""
    text = "" if value is None else str(value)
    text = re.sub(r"\s*[\r\n]+\s*", " ", text).strip()   # no new blocks/headings
    text = _MD_SPECIAL.sub(r"\\\1", text)              # no links/images/code/emphasis/tables
    return text.replace("<", "&lt;").replace(">", "&gt;")  # no raw HTML


def format_markdown(rca: dict, context: dict, findings: list[str] | None = None) -> str:
    """
    Render the RCA dict as a structured markdown postmortem document.
    `findings` come from guard.apply_guard(); any finding marks the draft
    UNVERIFIED at the top of the document.
    """
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    lines = []

    # Header
    title = md(rca.get("title", "Incident Postmortem"))
    severity = md(rca.get("severity", "Unknown"))
    lines += [
        f"# {title}",
        f"",
        f"| Field | Value |",
        f"|---|---|",
        f"| **Severity** | {severity} |",
        f"| **Start** | {md(context['start_time'])} |",
        f"| **End** | {md(context['end_time'])} |",
        f"| **Duration** | {context['duration_minutes']} minutes |",
        f"| **Alert** | {md(context['alert'])} |",
        f"| **Log Group** | {md(context['log_group'])} |",
        f"| **Generated** | {now} |",
        f"",
    ]

    if findings:
        lines += [
            f"> ⚠️ **UNVERIFIED — the output guard changed {len(findings)} thing(s) in this "
            f"draft.** Check these before acting on it:",
            ">",
        ]
        lines += [f"> - {md(f)}" for f in findings]
        lines.append("")

    # Summary
    lines += [
        "## Summary",
        "",
        md(rca["summary"]) if rca.get("summary") else "_No summary generated._",
        "",
    ]

    # Impact
    lines += [
        "## Impact",
        "",
        md(rca["impact"]) if rca.get("impact") else "_Unknown_",
        "",
    ]

    # Root Cause
    lines += [
        "## Root Cause",
        "",
        md(rca["root_cause"]) if rca.get("root_cause") else "_Could not determine root cause from available data._",
        "",
    ]

    # Deploy Correlation
    deploy_correlation = rca.get("deploy_correlation")
    if deploy_correlation:
        lines += [
            "## Deploy Correlation",
            "",
            md(deploy_correlation),
            "",
        ]

    # Contributing Factors
    factors = rca.get("contributing_factors", [])
    if factors:
        lines += ["## Contributing Factors", ""]
        for f in factors:
            lines.append(f"- {md(f)}")
        lines.append("")

    # Timeline
    timeline = rca.get("timeline", [])
    if timeline:
        lines += ["## Timeline", ""]
        for event in timeline:
            lines.append(f"- **{md(event.get('time', ''))}** — {md(event.get('event', ''))}")
        lines.append("")

    # Hypotheses (if root cause uncertain)
    hypotheses = rca.get("hypotheses", [])
    if hypotheses:
        lines += ["## Alternative Hypotheses", ""]
        for h in hypotheses:
            lines.append(f"- {md(h)}")
        lines.append("")

    # Action Items
    action_items = rca.get("action_items", [])
    if action_items:
        lines += [
            "## Action Items",
            "",
            "| Priority | Action | Owner |",
            "|---|---|---|",
        ]
        for item in action_items:
            priority = md(item.get("priority", "medium"))
            action = md(item.get("action", ""))
            owner = md(item.get("owner", "TBD"))
            lines.append(f"| {priority.upper()} | {action} | {owner} |")
        lines.append("")

    # Footer
    lines += [
        "---",
        "",
        "_Generated by [logmortem](https://github.com/sagecanty/Logmortem)_",
        "",
    ]

    return "\n".join(lines)


def print_summary(context: dict) -> None:
    """
    Print a human-readable summary of collected context to terminal.
    Used in --dry-run mode.
    """
    print(f"  Log Group:       {context['log_group']}")
    print(f"  Start:           {context['start_time']}")
    print(f"  End:             {context['end_time']}")
    print(f"  Duration:        {context['duration_minutes']} minutes")
    print(f"  Alert:           {context['alert']}")
    print(f"  Log Events:      {context['total_log_events']} total, "
          f"{context['error_log_count']} errors")
    if context.get("redacted_values"):
        print(f"  Redacted:        {context['redacted_values']} secret/personal value(s) "
              f"removed before prompting")
    print()

    if context.get("error_logs"):
        print("  TOP ERROR LOGS:")
        for e in context["error_logs"][:5]:
            print(f"    [{e['timestamp']}] {e['message'][:120]}")
        print()

    if context.get("deploys"):
        print("  RECENT DEPLOYS:")
        for d in context["deploys"][:5]:
            print(f"    [{d['time']}] {d['workflow']} — "
                  f"{d['status']} (commit {d['commit']}: {d['commit_message'][:60]})")
        print()
    else:
        print("  DEPLOYS: None collected\n")
